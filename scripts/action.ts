// Builds the self-contained GitHub Action and its licenses. --check compares without writing, so CI tests
// the artifact that users receive rather than silently replacing it with a fresh build.

import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { build } from 'esbuild';

const root = fileURLToPath(new URL('../', import.meta.url));
const check = process.argv.includes('--check');
if (process.argv.slice(2).some((arg) => arg !== '--check')) throw new Error('Usage: node scripts/action.ts [--check]');

const result = await build({
  absWorkingDir: root,
  entryPoints: ['action/index.ts'],
  bundle: true,
  platform: 'node',
  // jsonc-parser also ships UMD code whose factory hides require() calls from static bundlers.
  mainFields: ['module', 'main'],
  target: 'node24',
  format: 'cjs',
  outfile: 'action/dist/index.cjs',
  write: false,
  metafile: true,
  legalComments: 'eof',
  banner: { js: '// Generated by npm run build:action. Licenses: LICENSES.txt. Do not edit by hand.' },
});

const files = new Map(result.outputFiles.map((file) => [file.path, file.text]));
const licenses = [readFileSync(join(root, 'LICENSE'), 'utf8'), readFileSync(join(root, 'THIRD-PARTY-NOTICES.md'), 'utf8')];
const packages = new Map<string, string>();
for (const input of Object.keys(result.metafile.inputs)) {
  if (!input.includes('node_modules/')) continue;
  for (let folder = dirname(resolve(root, input)); folder !== dirname(folder); folder = dirname(folder)) {
    const manifest = join(folder, 'package.json');
    if (!existsSync(manifest)) continue;
    const metadata = JSON.parse(readFileSync(manifest, 'utf8')) as { name: string; version: string };
    packages.set(`${metadata.name}@${metadata.version}`, folder);
    break;
  }
}
for (const [name, folder] of [...packages].sort(([a], [b]) => a.localeCompare(b, 'en'))) {
  const names = readdirSync(folder).filter((file) => /^(?:licen[sc]e|copying)(?:\.|$)/i.test(file)).sort();
  if (names.length === 0) throw new Error(`No license found for bundled dependency ${name}`);
  licenses.push(`## ${name}\n\n${names.map((file) => readFileSync(join(folder, file), 'utf8')).join('\n\n')}`);
}
files.set(join(root, 'action/dist/LICENSES.txt'), licenses.join('\n\n') + '\n');

let differs = false;
for (const [file, generated] of files) {
  // Dependency licenses may use CRLF; match the LF files that .gitattributes checks out on every system.
  const content = generated.replace(/\r\n?/g, '\n').trimEnd() + '\n';
  if (check) {
    if (!existsSync(file) || readFileSync(file, 'utf8') !== content) {
      process.stderr.write(`${file}: differs from the sources. Run npm run build:action.\n`);
      differs = true;
    }
  } else {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, content);
  }
}
if (differs) process.exitCode = 1;
